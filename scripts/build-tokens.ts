// Turns src/tokens/theme.json (exported from the Theme Lab) into src/tokens/theme.css.
// Run with: pnpm tokens   (Node runs this TypeScript file directly.)
import { readFileSync, writeFileSync } from "node:fs";

type Mode = { scales: Record<string, string[]>; semantic: Record<string, string> };
type Theme = {
  inputs: { density: number; font: string };
  radius: { sm: number; md: number; lg: number };
  fontSize: Record<string, number>;
  light: Mode;
  dark: Mode;
};

const root = new URL("../src/tokens/", import.meta.url);
const theme = JSON.parse(readFileSync(new URL("theme.json", root), "utf8")) as Theme;

// Tokens derived here rather than in the Theme Lab: the dimmed backdrop behind dialogs.
const hue = (theme.inputs as unknown as { hue: number }).hue;
const extras: Record<"light" | "dark", Record<string, string>> = {
  light: { overlay: `oklch(20% 0.02 ${hue} / 0.45)` },
  dark: { overlay: "oklch(0% 0 0 / 0.6)" },
};

const vars = (mode: Mode, name: "light" | "dark") =>
  Object.entries({ ...mode.semantic, ...extras[name] })
    .map(([name, value]) => `  --ds-${name}: ${value};`)
    .join("\n");

const colorNames = [...Object.keys(theme.light.semantic), ...Object.keys(extras.light)];
const fontSizes = Object.entries(theme.fontSize)
  .map(([k, v]) => `  --text-${k}: ${(v / 16).toFixed(4).replace(/0+$/, "")}rem;`)
  .join("\n");

const css = `/* GENERATED by scripts/build-tokens.ts from theme.json. Do not edit by hand: run \`pnpm tokens\`. */

/* Raw values, light mode by default. */
:root {
${vars(theme.light, "light")}
}

/* Dark mode: add class="dark" (or data-theme="dark") on <html> or any container. */
.dark,
[data-theme="dark"] {
${vars(theme.dark, "dark")}
  color-scheme: dark;
}

/*
 * Tailwind theme. The default Tailwind palette is removed on purpose (--color-*: initial),
 * so only the semantic colors below exist: bg-surface, text-muted, border-strong, bg-accent...
 */
@theme inline {
  --color-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
${colorNames.map((n) => `  --color-${n}: var(--ds-${n});`).join("\n")}

  /* Spacing: every p-*, m-*, gap-* is a multiple of this unit (the 4px grid, scaled by density). */
  --spacing: ${4 * theme.inputs.density}px;

  --radius-sm: ${theme.radius.sm}px;
  --radius-md: ${theme.radius.md}px;
  --radius-lg: ${theme.radius.lg}px;

  --font-sans: "${theme.inputs.font} Variable", "${theme.inputs.font}", ui-sans-serif, system-ui, sans-serif;
${fontSizes}
}
`;

writeFileSync(new URL("theme.css", root), css);
console.log(`Wrote src/tokens/theme.css (${colorNames.length} colors per mode).`);
